  /**
  Creates a new entity of a specified type and optionally initializes it. By default the new entity is created with an EntityState of Added
  but you can also optionally specify an EntityState.  An EntityState of 'Detached' will insure that the entity is created but not yet added
  to the EntityManager. 
  ```ts
  // assume em1 is an EntityManager containing a number of preexisting entities.
  // create and add an entity. Passing the registered class types the result:
  const emp1 = em1.createEntity(Employee);            // Employee
  // create and add an initialized entity;
  const emp2 = em1.createEntity(Employee, { lastName: "Smith", firstName: "John" });
  // create and attach (not add) an initialized entity
  const emp3 = em1.createEntity(Employee, { employeeID: 435, lastName: "Smith", firstName: "John" }, EntityState.Unchanged);
  // create but don't attach an entity;
  const emp4 = em1.createEntity(Employee, { employeeID: 435, lastName: "Smith", firstName: "John" }, EntityState.Detached);
  // with the constructor, initialValues is checked: a property Employee does not declare,
  // such as a misspelling, is a compile error rather than a value silently ignored
  em1.createEntity(Employee, { lastNmae: "Smith" });   // error

  // the type name and the EntityType both still work, and return Entity:
  const emp5 = em1.createEntity("Employee", { lastName: "Smith" });
  ```

  The constructor overload needs the class to have been registered with
  {@link MetadataStore.registerEntityTypeCtor}; that is what tells Breeze which type it stands
  for. An unregistered class throws. See the Typed entities guide.
  @param entityCtor - A constructor registered for the EntityType to create.
  @param typeName - The name of the EntityType for which an instance should be created.
  @param entityType - The EntityType of the type for which an instance should be created.
  @param initialValues - (default=null) Configuration object of the properties to set immediately after creation.
  With the constructor overload it is typed as {@link InitialValues}, so a property the class does
  not declare is a compile error.
  @param entityState - (default = {@link EntityState.Added}) The EntityState of the entity after being created and added to this EntityManager.
  @param mergeStrategy - (default = {@link MergeStrategy.Disallowed}) - How to handle conflicts if an entity with the same key already exists within this EntityManager.
  @returns {Entity} A new Entity of the specified type. 
  */
  createEntity(entityType: EntityType | string | (new () => Entity), initialValues: Object, entityState: EntityState, mergeStrategy: MergeStrategy) {
    // A constructor stands for its type *name*, which is then looked up in this manager's own
    // MetadataStore. Using the EntityType hanging off the constructor's prototype would tie the
    // call to whichever store the class was registered with, and a manager with an equivalent
    // store - a copy, or one built from the same metadata - would fail deep inside attachEntity
    // with a store-mismatch error.
    if (typeof entityType === "function") {
      entityType = entityTypeForCtor(entityType).name;
    }
    assertParam(entityType, "entityType").isString().or().isInstanceOf(EntityType).check();
    assertParam(entityState, "entityState").isEnumOf(EntityState).isOptional().check();
    assertParam(mergeStrategy, "mergeStrategy").isEnumOf(MergeStrategy).isOptional().check();

    let et = (typeof entityType === "string") ? this.metadataStore._getStructuralType(entityType) as EntityType : entityType;
    entityState = entityState || EntityState.Added;
    let entity = {} as Entity;
    core.using(this, "isLoading", true, function () {
      entity = et.createEntity(initialValues);
    });
    if (entityState !== EntityState.Detached) {
      // The two enums were checked above; no need for attachEntity to check them again.
      entity = this._attachEntity(entity, entityState, mergeStrategy || MergeStrategy.Disallowed);
    }
    return entity;
  }

