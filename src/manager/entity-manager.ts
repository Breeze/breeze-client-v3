// takes in entityTypes as either strings or entityTypes or arrays of either
// and returns either an entityType or an array of entityTypes or throws an error
function checkEntityTypes(em: EntityManager, entityTypes?: EntityTypeArg | EntityTypeArg[]) {
  // A registered constructor stands for its type name, which is resolved against this manager's
  // own store - see the note in createEntity. Normalized before the assertions, so the rest of
  // this, and every caller, is the 2.x path unchanged.
  if (typeof entityTypes === "function") {
    entityTypes = entityTypeForCtor(entityTypes).name;
  } else if (Array.isArray(entityTypes) && entityTypes.some(t => typeof t === "function")) {
    entityTypes = (entityTypes as EntityTypeArg[]).map(t => typeof t === "function" ? entityTypeForCtor(t).name : t) as string[];
  }
  assertParam(entityTypes as any, "entityTypes").isString().isOptional().or().isNonEmptyArray().isString()
    .or().isInstanceOf(EntityType).or().isNonEmptyArray().isInstanceOf(EntityType).check();
  let resultTypes: EntityType | EntityType[] | undefined;
  if (typeof entityTypes === "string") {
    resultTypes = em.metadataStore._getStructuralType(entityTypes, false) as (EntityType | EntityType[]);
  } else if (Array.isArray(entityTypes) && typeof entityTypes[0] === "string") {
    resultTypes = (entityTypes as string[]).map(function (etName) {
      return em.metadataStore._getStructuralType(etName, false) as EntityType;
    });
  } else {
    resultTypes = entityTypes as (EntityType | EntityType[] | undefined);
  }

  return resultTypes;
}

function getChangesCore(em: EntityManager, entityTypes?: EntityType | EntityType[]) {
  let entityGroups = getEntityGroups(em, entityTypes);

  // TODO: think about writing a core.mapMany method if we see more of these.
  let selected: Entity[] = [];
  entityGroups.forEach(function (eg) {
    // eg may be undefined or null
    if (!eg) return;
    let entities = eg.getChanges();
    if (selected && selected.length) {
      selected = selected.concat(entities);
    } else {
      selected = entities;
    }
  });
  return selected;
}

function getEntitiesCore(em: EntityManager, entityTypes: EntityType | EntityType[] | undefined, entityStates: EntityState[]) {
  let entityGroups = getEntityGroups(em, entityTypes);

  // TODO: think about writing a core.mapMany method if we see more of these.
  let selected: Entity[] = [];
  entityGroups.forEach(function (eg) {
    // eg may be undefined or null
    if (!eg) return;
    let entities = eg.getEntities(entityStates);
    if (selected && selected.length) {
      selected = selected.concat(entities);
    } else {
      selected = entities;
    }
  });
  return selected;
}


function createEntityKey(em: EntityManager, args: any[]) {
  if (args[0] instanceof EntityKey) {
    return { entityKey: args[0] as EntityKey, remainingArgs: arraySlice(args, 1) };
  }
  if (args.length >= 2) {
    let entityType: any;
    try {
      entityType = (typeof args[0] === 'string') ? em.metadataStore._getStructuralType(args[0], false)
        : (typeof args[0] === 'function') ? em.metadataStore._getStructuralType(entityTypeForCtor(args[0]).name, false) : args[0];
    } catch (e) { /* not a type: the error below says what is expected */ }
    if (entityType instanceof EntityType) {
      // Outside the try: an error about the key values - a name that is not part of the key, a key
      // property with no value - says more than the one below.
      return { entityKey: new EntityKey(entityType, args[1]), remainingArgs: arraySlice(args, 2) };
    }
  }
  throw new Error("Must supply an EntityKey OR an EntityType name or EntityType followed by a key value or an array of key values.");
}

