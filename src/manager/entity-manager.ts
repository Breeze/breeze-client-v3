/** Whether any of these entities has an async validator, on its type, a property, or a complex type
it holds. Looked up once per type: validators can be added at any time, so it is not cached. */
function hasAsyncValidators(entities: Entity[]) {
  const seen = new Set<StructuralType>();
  const typeHasAsync = (stype: StructuralType): boolean => {
    if (seen.has(stype)) return false;
    seen.add(stype);
    if (stype.getAllValidators().some(v => v.isAsync)) return true;
    return stype.getProperties().some((p: any) =>
      p.getAllValidators().some((v: Validator) => v.isAsync) ||
      (p.isComplexProperty && typeHasAsync(p.dataType as StructuralType)));
  };
  return entities.some(e => !e.entityAspect.entityState.isDeleted() && typeHasAsync(e.entityType));
}

function clearServerErrors(entities: Entity[]) {
  entities.forEach(function (entity) {
    let serverKeys: string[] = [];
    let aspect = entity.entityAspect;
    core.objectForEach(aspect._validationErrors, function (key, ve) {
      if (ve.isServerError) serverKeys.push(key);
    });
    if (serverKeys.length === 0) return;
    aspect._processValidationOpAndPublish(function () {
      serverKeys.forEach(function (key) {
        aspect._removeValidationError(key);
      });
    });
  });
}

function createEntityErrors(entities: Entity[]) {
  let entityErrors: EntityError[] = [];
  entities.forEach((entity) => {
    core.objectForEach(entity.entityAspect._validationErrors, function (key, ve) {
      let cfg = core.extend({
        entity: entity,
        // An error added with addValidationError has no validator. Reading one threw a TypeError,
        // which replaced the whole validation error - and its entityErrors - with "Cannot read
        // properties of undefined". Such an error is named by its key.
        errorName: ve.validator ? ve.validator.name : ve.key
      }, ve, ["errorMessage", "propertyName", "isServerError", "custom"]) as EntityError;
      entityErrors.push(cfg);
    });
  });
  return entityErrors;
}


function processServerErrors(saveContext: SaveContext, saveError: SaveErrorFromServer) {
  // converting ISaveErrorFromServer -> ISaveError
  let serverErrors = saveError.entityErrors;
  if (!serverErrors) return <SaveError> <any> saveError;
  let entityManager = saveContext.entityManager;
  let metadataStore = entityManager.metadataStore;
  let entityErrors = serverErrors.map((serr) => {
    let entity: Entity | null = null;
    let entityType: EntityType | undefined;
    if (serr.keyValues) {
      entityType = metadataStore._getStructuralType(serr.entityTypeName) as EntityType;
      let ekey = new EntityKey(entityType, serr.keyValues);
      entity = entityManager.getEntityByKey(ekey);
    }

    if (entityType && entity) {
      let context = serr.propertyName ?
        {
          propertyName: serr.propertyName,
          property: entityType.getProperty(serr.propertyName) || undefined
        } : {
        };
      let key = ValidationError.getKey(serr.errorName || serr.errorMessage, serr.propertyName);

      let ve = new ValidationError(null, context, serr.errorMessage, key);
      ve.isServerError = true;
      entity.entityAspect.addValidationError(ve);
    }

    let entityError = core.extend({
      entity: entity,
      isServerError: true
    }, serr, ["errorName", "errorMessage", "propertyName", "custom"]) as EntityError;
    return entityError;
  });
  // converting ISaveErrorFromServer -> ISaveError 
  saveError.entityErrors = entityErrors as any;
  return <SaveError> <any> saveError;
}

/** What an {@link EntityManager.fetchEntityByKey} call resolves with. */
export interface IEntityByKeyResult {
  /** The entity, or `null` if there is none.

  `null` rather than `undefined`, because that is what absence means everywhere else in Breeze:
  a scalar navigation property with nothing cached is `null`, a nullable data property is `null`,
  and {@link EntityManager.getEntityByKey} returns `null`. Before 3.0 this one property was the
  exception. See UPGRADE.md. */
  entity: Entity | null;
  /** The key that was looked up. */
  entityKey: EntityKey;
  /** True if the answer came from the local cache, which is only checked when `checkLocalCacheFirst`
  is true; false if the server was queried. It can be true with a null `entity`: the cached entity is
  Deleted, and the manager's `queryOptions` exclude deleted entities and do not use
  {@link MergeStrategy.OverwriteChanges}. */
  fromCache: boolean;
}

/** {@link IEntityByKeyResult} for a known entity type - what the constructor overload of
{@link EntityManager.fetchEntityByKey} returns. */
export interface EntityByKeyResult<T extends Entity> extends IEntityByKeyResult {
  entity: T | null;
}

function fetchEntityByKeyCore(em: EntityManager, args: any[]): Promise<IEntityByKeyResult> {
  let tpl = createEntityKey(em, args);
  let entityKey = tpl.entityKey;

  let checkLocalCacheFirst = tpl.remainingArgs.length === 0 ? false : !!tpl.remainingArgs[0];
  let entity: Entity | null = null;
  let foundIt = false;
  if (checkLocalCacheFirst) {
    entity = em.getEntityByKey(entityKey);
    foundIt = entity != null;
    if (entity != null &&
      // null the entity if it is deleted and we should exclude deleted entities
      !em.queryOptions.includeDeleted && entity.entityAspect.entityState.isDeleted()) {
      entity = null;
      // but resume looking if we'd overwrite deleted entity with a remote entity
      // note: em.queryOptions is always fully resolved by now
      foundIt = em.queryOptions.mergeStrategy !== MergeStrategy.OverwriteChanges;
    }
  }
  if (foundIt) {
    return Promise.resolve({ entity: entity, entityKey: entityKey, fromCache: true });
  } else {
    return EntityQuery.fromEntityKey(entityKey).using(em).execute().then(function (data: any) {
      entity = (data.results.length === 0) ? null : data.results[0];
      return Promise.resolve({ entity: entity, entityKey: entityKey, fromCache: false });
    });
  }
}


