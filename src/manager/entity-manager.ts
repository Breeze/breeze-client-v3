/** Base shape of any errors returned from the server. */
export interface ServerError extends Error {
  /** The failed response, for anything the other members do not cover. */
  httpResponse: HttpResponse;
  /** The HTTP status code - see {@link HttpResponse.status}. `0` when the request failed before any
  response arrived. */
  status: number;
  /** The best description Breeze could find: the message in the response body (a .NET exception's
  message, or the `message`, `detail` or `title` of a JSON error), otherwise the transport's error
  text. When the status is `0`, it also says the server was probably not reached. */
  message: string;
  /** The status text of the failed response - see {@link HttpResponse.statusText}. */
  statusText?: string;
  /** The body of the failed response, as the adapter received it (`httpResponse.data`); null if there was none. */
  body?: any;
  /** The URL the request was sent to (`httpResponse.config.url`). Query parameters added with
  `EntityQuery.withParameters` are not included. */
  url?: string;
  /** The RFC 9457 `type` member of the problem document, when the server sent one: a URI naming
  what kind of problem this is.

  Read it rather than the message when the recovery depends on the kind of failure. The status
  code is often not enough on its own - an optimistic concurrency conflict and a duplicate key are
  both `409`, and they are recovered from differently - and message text is not something to match
  on, since it varies by ORM, database and server version.

  Undefined when the server sent no `type`, which is every pre-3.0 Breeze server and most
  non-Breeze ones. See {@link ProblemTypes} and {@link isConcurrencyError}. */
  problemType?: string;
}

