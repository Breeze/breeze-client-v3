/**
 * Groups the API reference by what each symbol is *for*, instead of by what kind of
 * declaration it happens to be.
 *
 * Without this, the sidebar is five flat buckets - Classes, Interfaces, Type aliases,
 * Functions, Variables - and "Interfaces" alone is sixty entries in which `Entity` sits
 * beside `NodeMeta`. The categories below put the everyday surface first and push the
 * plumbing (constructor config bags, adapter contracts, the typed-query path machinery,
 * the 2.x leftovers) to the bottom, collapsed.
 *
 * Nothing is hidden. Every symbol still has a page, because these are all genuinely
 * exported: marking one `@internal` would be a lie to anyone reading the .d.ts, and
 * dropping a page leaves dangling links from the pages that reference it - TypeDoc warns
 * about exactly that. De-emphasis is what is wanted here, not removal. If a category ever
 * does need to disappear from the site, add its name to `excludeCategories`.
 *
 * --- why the table lives here, rather than as @category tags in the source ---
 *
 * `@category` is a doc-comment tag, so the conventional way to apply it is one tag per
 * symbol across the twenty-odd files that export them. A single table is easier to review
 * as a taxonomy - you can see at a glance that `Entity` and `NodeMeta` ended up in
 * different places - and it keeps a purely presentational concern out of the source.
 *
 * The cost of that choice is drift: a table in one file cannot be kept honest by the
 * compiler. So the plugin checks itself, and warns when the table names something that no
 * longer exists, or when a newly exported symbol is missing from it. A new export lands in
 * a named category or it makes noise; it cannot quietly fall into "Other".
 *
 * Timing matters. This hooks EVENT_CREATE_DECLARATION, during conversion. Tagging later,
 * on EVENT_RESOLVE_BEGIN, renders the categories correctly but is too late for
 * `excludeCategories`, which then silently ignores them.
 */
import { Comment, CommentTag, Converter, ReflectionKind } from 'typedoc';

