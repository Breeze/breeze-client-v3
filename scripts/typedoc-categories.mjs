/** The kinds that appear as top-level entries in the sidebar. */
const TOP_LEVEL =
  ReflectionKind.Class | ReflectionKind.Interface | ReflectionKind.TypeAlias |
  ReflectionKind.Function | ReflectionKind.Variable | ReflectionKind.Namespace |
  ReflectionKind.Enum;

const CATEGORY_OF = new Map();
for (const [category, names] of Object.entries(CATEGORIES)) {
  for (const name of names) {
    if (CATEGORY_OF.has(name)) throw new Error(`typedoc-categories: ${name} is in two categories`);
    CATEGORY_OF.set(name, category);
  }
}

export function load(app) {
  const tagged = new Set();

  app.converter.on(Converter.EVENT_CREATE_DECLARATION, (_context, refl) => {
    // Matching by name only makes sense at the top level: `EntityManager` is also a
    // property of the `breeze` compatibility object, and every class has members of its own.
    if (!refl.parent?.isProject() || !refl.kindOf(TOP_LEVEL)) return;
    const category = CATEGORY_OF.get(refl.name);
    if (!category) return;
    refl.comment ??= new Comment();
    refl.comment.blockTags.push(new CommentTag('@category', [{ kind: 'text', text: category }]));
    tagged.add(refl.name);
  });

  // Keep the table honest against a source tree that will keep moving.
  app.converter.on(Converter.EVENT_RESOLVE_BEGIN, (context) => {
    const documented = (context.project.children ?? [])
      .filter(c => c.kindOf(TOP_LEVEL))
      .map(c => c.name);

    const missing = documented.filter(n => !CATEGORY_OF.has(n));
    if (missing.length) {
      app.logger.warn(
        'typedoc-categories: uncategorised, so these land under "Other": ' + missing.join(', ') +
        '. Add them to scripts/typedoc-categories.mjs.');
    }

    const stale = [...CATEGORY_OF.keys()].filter(n => !tagged.has(n));
    if (stale.length) {
      app.logger.warn(
        'typedoc-categories: categorised but no longer documented: ' + stale.join(', ') +
        '. Remove them from scripts/typedoc-categories.mjs.');
    }
  });
}
